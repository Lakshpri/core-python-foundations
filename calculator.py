# ============================================================
# ADDITION
# ============================================================

def add(a, b):

    return a + b


# ============================================================
# SUBTRACTION
# ============================================================

def subtract(a, b):

    return a - b


# ============================================================
# MULTIPLICATION
# ============================================================

def multiply(a, b):

    return a * b


# ============================================================
# DIVISION
# ============================================================

def divide(a, b):

    if b == 0:

        return "Cannot divide by zero."

    return a / b